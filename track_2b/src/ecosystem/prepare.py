def sha(data): return hashlib.sha256(data).hexdigest()


def runtime_path(relative):
    path=Path(relative)
    root=RUNTIME.resolve();target=(root/path).resolve()
    if path.is_absolute() or PureWindowsPath(relative).drive or '..' in PureWindowsPath(relative).parts or not target.is_relative_to(root) or target==root:
        raise ValueError('Fixture path must stay inside its private runtime directory')
    return target


def write_json(path, value):
    path=Path(path);path.parent.mkdir(parents=True,exist_ok=True)
    temporary=path.with_name(path.name+'.'+uuid.uuid4().hex+'.tmp')
    # Preserve the already frozen Windows-generated byte hashes on Linux too.
    temporary.write_text(json.dumps(value,ensure_ascii=False,indent=2)+'\n',encoding='utf-8',newline='\r\n')
    try:
        for attempt in range(6):
            try:temporary.replace(path);break
            except PermissionError:
                if attempt==5:raise
                time.sleep(.05*(attempt+1))
    finally:
        temporary.unlink(missing_ok=True)


def download(key,path,expected=None,maximum=10*1024*1024):
    source=SOURCES[key]
    if '..' in Path(path).parts or Path(path).is_absolute(): raise ValueError('Unsafe source path')
    target=RUNTIME/'sources'/key/path
    url=f"https://huggingface.co/datasets/{source['repo']}/resolve/{source['revision']}/{quote(path)}"
    lock=PUBLIC/'sources.lock.json'
    if expected is None and lock.exists():
        known=json.loads(lock.read_text(encoding='utf-8'))
        pinned=[f for f in known['files'] if f['dataset']==key and f['path']==path and f['revision']==source['revision']]
        if pinned: expected=pinned[0]['sha256']
    if target.exists():
        data=target.read_bytes()
    else:
        with urllib.request.urlopen(urllib.request.Request(url,headers={'User-Agent':VERSION}),timeout=60) as response:
            data=response.read(maximum+1)
        if len(data)>maximum: raise ValueError('Source exceeds bounded download size')
        target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(data)
    if len(data)>maximum or (expected and sha(data)!=expected): raise ValueError('Source checksum mismatch: '+path)
    return data, {'dataset':key,'revision':source['revision'],'path':path,'url':url,'sha256':sha(data),'bytes':len(data),'license':source['license']}


def normalize(value):
    counts={old:value.count(old) for old in FIXUPS if old in value}
    for old,new in FIXUPS.items(): value=value.replace(old,new)
    return value,counts


def date_parts(value):
    for fmt in ('%d/%m/%Y %H:%M','%d/%m/%Y','%Y-%m-%d'):
        try:
            day=datetime.strptime(value.strip(),fmt).date()
            return {'precision':'day','year':day.year,'month':day.month,'day':day.day}
        except ValueError: pass
    return {'precision':'unknown','year':None,'month':None,'day':None}


def load_sources():
    locked=[]
    for key,source in SOURCES.items():
        for path,expected in source['files'].items():
            _,entry=download(key,path,expected);locked.append(entry)
    def rows(name): return list(csv.DictReader(io.StringIO((RUNTIME/'sources/nhs/silver'/name).read_text(encoding='utf-8-sig'))))
    patients=rows('patients.csv');admissions=rows('admissions.csv');notes=rows('synthetic_clinical_notes.csv')
    def unique(items,field):
        result={}
        for row in items:
            if row[field] in result and result[row[field]]!=row:
                raise ValueError('Conflicting duplicate source identifier: '+field)
            result[row[field]]=row
        return result
    people=unique(patients,'person_id');encounters=unique(admissions,'admission_id');unique(notes,'clinical_note_id')
    groups=defaultdict(list)
    for note in notes:
        if note['person_id'] not in people or note['admission_id'] not in encounters or encounters[note['admission_id']]['patient_id']!=note['person_id']:
            raise ValueError('NHS source relationship mismatch')
        groups[note['person_id']].append(note)
    for group in groups.values(): group.sort(key=lambda n:(datetime.strptime(n['creation_timestamp'],'%d/%m/%Y %H:%M'),n['clinical_note_id']))
    return people,encounters,groups,locked


