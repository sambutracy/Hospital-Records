def validate_manifest(manifest):
    if manifest.get('version')!=VERSION or manifest.get('synthetic_only') is not True: raise ValueError('Synthetic manifest required')
    docs=manifest['documents']+manifest.get('auxiliary_documents',[])
    if len({d['id'] for d in docs})!=len(docs): raise ValueError('Duplicate fixture IDs')
    if any(not re.fullmatch(r'[A-Za-z0-9-]{1,100}',d['id']) for d in docs): raise ValueError('Unsafe fixture ID')
    people=manifest['patients'];seen=set()
    for person in people:
        pid=person['source_patient_id']
        if pid in seen: raise ValueError('Source patient reused across workspaces')
        seen.add(pid)
        assigned=[d for d in manifest['documents'] if d['patient']==person['id']]
        if set(person['documents'])!={d['id'] for d in assigned}: raise ValueError('Patient document map mismatch')
        if any(d['source_patient_id']!=pid for d in assigned): raise ValueError('Mixed source patients')
        if len(assigned)!=person['expected_initial_documents']: raise ValueError('Population count mismatch')
    for doc in docs:
        if 'text_path' in doc:
            data=runtime_path(doc['text_path']).read_bytes()
            if doc.get('normalized_text_sha256') and sha(data)!=doc['normalized_text_sha256']:
                # Text files are written with explicit UTF-8/newline preservation.
                # Python's Windows text writer expands LF to CRLF; compare logical
                # text for this upstream normalization digest.
                logical=runtime_path(doc['text_path']).read_text(encoding='utf-8')
                if sha(logical.encode())!=doc['normalized_text_sha256']:raise ValueError('Normalized source text changed')
        if 'prepared_path' in doc:
            data=runtime_path(doc['prepared_path']).read_bytes()
            if sha(data)!=doc['sha256']: raise ValueError('Prepared document checksum changed')
    lock=PUBLIC/'text.lock.json'
    if lock.exists():
        expected=json.loads(lock.read_text(encoding='utf-8'))
        observed={d['id']:sha(runtime_path(d['text_path']).read_text(encoding='utf-8').encode()) for d in docs if 'text_path' in d}
        if expected.get('files')!=observed:raise ValueError('Frozen reference text checksum changed')
    return True


def freeze_text(manifest):
    files={d['id']:sha(runtime_path(d['text_path']).read_text(encoding='utf-8').encode())
        for d in manifest['documents']+manifest.get('auxiliary_documents',[]) if 'text_path' in d}
    value={'version':VERSION,'encoding':'UTF-8; logical LF text','files':files}
    target=PUBLIC/'text.lock.json'
    if target.exists() and json.loads(target.read_text(encoding='utf-8'))!=value:raise ValueError('Reference text is frozen')
    write_json(target,value)
