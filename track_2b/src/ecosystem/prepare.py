def pdf_bytes(doc):
    from reportlab.pdfgen.canvas import Canvas
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    from reportlab.lib.utils import simpleSplit
    font=Path(__file__).parent/'assets'/'LiberationSans-Regular.ttf'
    if 'EcosystemSans' not in pdfmetrics.getRegisteredFontNames(): pdfmetrics.registerFont(TTFont('EcosystemSans',str(font)))
    output=io.BytesIO();canvas=Canvas(output,pagesize=(595,842),invariant=1,pageCompression=1)
    canvas.setTitle('Synthetic evaluation representation '+doc['id'])
    parts=doc['document_date']
    value='unknown' if parts['precision']=='unknown' else '-'.join(str(parts[x]).zfill(4 if x=='year' else 2) for x in ('year','month','day') if parts[x] is not None)
    lines=['SYNTHETIC EVALUATION REPRESENTATION - NOT A HOSPITAL ORIGINAL',
      'No real patient data. Not clinically validated. No diagnosis or treatment advice.',
      'Fixture: '+doc['id'],'Representation type: '+doc['document_type'],
      'Document date: '+value,'Source admission / authored facility: '+(doc['facility'] or 'not recorded'),
      'Source note / authored extension: '+doc['source_document_id'],'','SOURCE CONTENT:','']
    lines+=doc['text'].splitlines()
    canvas.setFont('EcosystemSans',9);y=800;page=1
    for raw in lines:
        for line in simpleSplit(raw.expandtabs(4),'EcosystemSans',9,507) or ['']:
            if y<58:
                canvas.drawString(44,34,f'{VERSION} | Page {page} | Synthetic only');canvas.showPage();canvas.setFont('EcosystemSans',9);page+=1;y=800
            canvas.drawString(44,y,line);y-=13
    canvas.drawString(44,34,f'{VERSION} | Page {page} | Synthetic only');canvas.save()
    return output.getvalue()


